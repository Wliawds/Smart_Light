/* ===== ????(CS=PB1, DC=PB2)===== */
#define LCD_CS_CLR()    (GPIOB->BSRR = (uint32_t)GPIO_PIN_1 << 16U)
#define LCD_CS_SET()    (GPIOB->BSRR = (uint32_t)GPIO_PIN_1)
#define LCD_DC_DATA()   (GPIOB->BSRR = (uint32_t)GPIO_PIN_2)
#define LCD_DC_CMD()    (GPIOB->BSRR = (uint32_t)GPIO_PIN_2 << 16U)

#define LCD_SPI         hspi1
#define TO              100             /* SPI??(ms),?????? */

/* ===== ??:??? / ??? ===== */
static void LCD_WriteCmd(uint8_t cmd)
{
    LCD_CS_CLR();
    LCD_DC_CMD();
    HAL_SPI_Transmit(&LCD_SPI, &cmd, 1, TO);
    LCD_DC_DATA();
    LCD_CS_SET();
}

static void LCD_WriteData(const uint8_t *buf, uint16_t len)
{
    LCD_CS_CLR();
    LCD_DC_DATA();
    HAL_SPI_Transmit(&LCD_SPI, (uint8_t *)buf, len, TO);
    LCD_CS_SET();
}

static inline void LCD_WriteData8(uint8_t d)
{
    LCD_CS_CLR();
    LCD_DC_DATA();
    HAL_SPI_Transmit(&LCD_SPI, &d, 1, TO);
    LCD_CS_SET();
}

static inline void LCD_WriteData16(uint16_t d)
{
    uint8_t t[2] = { (uint8_t)(d >> 8), (uint8_t)(d & 0xFF) };
    LCD_WriteData(t, 2);
}

/* ===== ???? ===== */
static void LCD_SetWindow(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2)
{
    uint8_t buf[4];
#if USE_ST7789
    int16_t yy1 = (int16_t)y1 + ST7789_YOFF;
    int16_t yy2 = (int16_t)y2 + ST7789_YOFF;
    if (yy1 < 0) yy1 = 0;
    if (yy2 > 319) yy2 = 319;
#else
    uint16_t yy1 = y1, yy2 = y2;
#endif

    LCD_WriteCmd(0x2A);
    buf[0] = (uint8_t)(x1 >> 8); buf[1] = (uint8_t)x1;
    buf[2] = (uint8_t)(x2 >> 8); buf[3] = (uint8_t)x2;
    LCD_WriteData(buf, 4);

    LCD_WriteCmd(0x2B);
    buf[0] = (uint8_t)(yy1 >> 8); buf[1] = (uint8_t)yy1;
    buf[2] = (uint8_t)(yy2 >> 8); buf[3] = (uint8_t)yy2;
    LCD_WriteData(buf, 4);

    LCD_WriteCmd(0x2C);
}

/* ===== ?? / ?? ===== */
void LCD_Clear(uint16_t color)
{
    LCD_Fill(0, 0, LCD_W - 1, LCD_H - 1, color);
}

void LCD_Fill(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    if (x1 >= LCD_W || y1 >= LCD_H) return;
    if (x2 >= LCD_W) x2 = LCD_W - 1;
    if (y2 >= LCD_H) y2 = LCD_H - 1;

    uint32_t n = (uint32_t)(x2 - x1 + 1) * (uint32_t)(y2 - y1 + 1);
    uint8_t pix[2] = { (uint8_t)(color >> 8), (uint8_t)(color & 0xFF) };

    LCD_SetWindow(x1, y1, x2, y2);
    LCD_CS_CLR();
    LCD_DC_DATA();
    while (n--) {
        HAL_SPI_Transmit(&LCD_SPI, pix, 2, TO);
    }
    LCD_CS_SET();
}

/* ===== ?? ===== */
void LCD_DrawPoint(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= LCD_W || y >= LCD_H) return;
    LCD_SetWindow(x, y, x, y);
    LCD_WriteData16(color);
}

