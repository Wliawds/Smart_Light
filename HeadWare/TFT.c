#define FONT_CNT  ((uint8_t)(sizeof(FONT)/sizeof(FONT[0])))

static const uint8_t* GetFont(char c)
{
    for (uint8_t i = 0; i < FONT_CNT; i++)
        if (FONT[i].c == c) return FONT[i].d;
    return NULL;
}

void LCD_ShowChar(uint16_t x, uint16_t y, char c, uint16_t color)
{
    const uint8_t *f = GetFont(c);
    if (!f) return;                         /* ???????,?????? */
    if (x + 7 >= LCD_W || y + 15 >= LCD_H) return;

    LCD_SetWindow(x, y, x + 7, y + 15);
    LCD_CS_CLR();
    LCD_DC_DATA();
    for (uint8_t i = 0; i < 16; i++) {
        uint8_t d = f[i];
        for (uint8_t j = 0; j < 8; j++) {
            LCD_WriteData16((d & 0x80) ? color : BLACK);
            d <<= 1;
        }
    }
    LCD_CS_SET();
}

void LCD_ShowString(uint16_t x, uint16_t y, const char *str, uint16_t color)
{
    while (*str && x + 7 < LCD_W && y + 15 < LCD_H) {
        LCD_ShowChar(x, y, *str, color);
        x += 8;
        str++;
    }
}

void LCD_ShowNum(uint16_t x, uint16_t y, uint32_t num, uint8_t len, uint16_t color)
{
    char buf[12];
    snprintf(buf, sizeof buf, "%0*lu", (int)len, (unsigned long)num);
    LCD_ShowString(x, y, buf, color);
}

void LCD_ShowFloat(uint16_t x, uint16_t y, float val, uint8_t len, uint16_t color)
{
    char buf[16];
    snprintf(buf, sizeof buf, "%*.1f", (int)len, (double)val);
    LCD_ShowString(x, y, buf, color);
}

